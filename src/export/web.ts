export interface WebOptions {
  responsive: boolean;
  breakpoint: number;
  scaleArtboard: boolean;
}
export const defaultWebOptions = (): WebOptions => ({
  responsive: true,
  breakpoint: 768,
  scaleArtboard: false,
});
export interface WebBundle {
  files: Record<string, string | Uint8Array>;
  pages: Record<string, string>;
  warnings: string[];
}
const baseCss = `/* Generated by XD Local. Layout and interaction rules are intentionally separate. */
* { box-sizing: border-box; }
html { scroll-behavior: smooth; }
body { margin: 0; background: #edf0f2; color: #16191d; }
[hidden] { display: none !important; }
button { font: inherit; color: inherit; padding: 0; border: 0; text-align: inherit; cursor: pointer; }
.board-shell { margin: 0 auto; position: relative; }
.artboard { position: relative; margin: 0 auto; isolation: isolate; }
.design-node { margin: 0; min-width: 0; transform-origin: 0 0; }
.component-state { position: absolute; inset: 0; }
.visual { display: block; width: 100%; height: 100%; overflow: visible; pointer-events: none; }
.visual svg { width: 100%; height: 100%; display: block; overflow: visible; }
[data-action] { cursor: pointer; }
[data-action]:focus-visible { outline: 3px solid #4361ee; outline-offset: 4px; }
.reveal-pending { opacity: 0 !important; translate: 0 24px; }
@keyframes xd-fade { from { opacity: 0; } }
@keyframes xd-slide { from { opacity: 0; translate: 0 24px; } }
@keyframes xd-pulse { 50% { scale: 1.04; } }
@media (prefers-reduced-motion: reduce) {
  *, *::before, *::after { animation: none !important; transition: none !important; scroll-behavior: auto !important; }
  .reveal-pending { opacity: 1 !important; translate: none !important; }
}
`;
export function exportWeb(project: Project, options: WebOptions = defaultWebOptions()): WebBundle {
  const files: WebBundle['files'] = {},
    pages: Record<string, string> = {},
    warnings: string[] = [];
  const boards = project.document.artboards,
    all = flatten(boards),
    ids = new Set(all.map((n) => n.id));
  boards.forEach((b, i) => (pages[b.id] = i === 0 ? 'index.html' : `page-${safeId(b.id)}.html`));
  const assetPaths: Record<string, string> = {};
  for (const asset of Object.values(project.document.assets)) {
    const extension = asset.mime.split('/')[1].replace('jpeg', 'jpg'),
      path = `assets/${safeId(asset.id)}.${extension}`;
    assetPaths[asset.id] = path;
    const binary = atob(asset.data.split(',')[1]);
    files[path] = Uint8Array.from(binary, (c) => c.charCodeAt(0));
  }
  const fontPaths: Record<string, string> = {};
  for (const font of Object.values(project.document.fonts ?? {})) {
    const path = `assets/${safeId(font.id)}.${font.mime.split('/')[1]}`;
    fontPaths[font.id] = path;
    files[path] = Uint8Array.from(atob(font.data.split(',')[1]), (c) => c.charCodeAt(0));
  }
  const rules: string[] = [baseCss, fontRules(project.document, undefined, fontPaths)],
    mediaRules: string[] = [];
  function node(
    n: DesignNode,
    parent: DesignNode | undefined,
    board: DesignNode,
    fixedAncestor = false,
    componentStates?: Set<string>
  ): string {
    const stateIds = n.component
      ? new Set([n.component.defaultState, ...n.component.states.map((s) => s.id)])
      : componentStates;
    const layout = project.layouts[n.id] ?? defaultLayout(),
      parentLayout = parent ? (project.layouts[parent.id] ?? defaultLayout()) : defaultLayout();
    const flow = options.responsive && parentLayout.mode !== 'absolute',
      isBoard = n.kind === 'artboard';
    const b = n.bounds,
      m = n.transform,
      x = m[4] + m[0] * b.x + m[2] * b.y - (parent?.bounds.x ?? 0),
      y = m[5] + m[1] * b.x + m[3] * b.y - (parent?.bounds.y ?? 0);
    const className = `xd-${
      filename(n.name)
        .replace(/[^a-zA-Z0-9_-]/g, '-')
        .replace(/^-+|-+$/g, '')
        .slice(0, 32) || n.kind
    }-${safeId(n.id)}`;
    const vector = n.kind === 'path' || n.kind === 'line';
    const svgAppearance =
      vector ||
      n.kind === 'ellipse' ||
      n.style.fill.type === 'linear' ||
      n.style.fill.type === 'radial' ||
      (n.style.fill.type === 'image' && !!n.style.fill.transform) ||
      !!n.style.stroke?.dash?.length;
    const selector = '.' + className,
      rule: Record<string, string> = {
        position: isBoard ? 'relative' : flow ? 'relative' : 'absolute',
        width: `${round(vector ? Math.max(1, b.width) : b.width)}px`,
        height: `${round(vector ? Math.max(1, b.height) : b.height)}px`,
        opacity: String(n.style.opacity),
      };
    if (!isBoard && !flow) Object.assign(rule, { left: `${round(x)}px`, top: `${round(y)}px` });
    if (flow) Object.assign(rule, { 'flex-shrink': '0', 'max-width': '100%' });
    if (m[0] !== 1 || m[1] !== 0 || m[2] !== 0 || m[3] !== 1)
      rule.transform = `matrix(${m.slice(0, 4).map(round).join(', ')}, 0, 0)`;
    if (n.fixed && !fixedAncestor) {
      const world = worldBounds(board, n.id);
      Object.assign(rule, {
        position: 'fixed',
        left: `${round(world?.x ?? x)}px`,
        top: `${round(world?.y ?? y)}px`,
        isolation: 'isolate',
      });
    }
    const interaction = project.interactions[n.id] ?? {};
    const attributes: Record<string, string> = {
      id: safeId(n.id),
      class: `${isBoard ? 'artboard' : 'design-node'} ${className}`,
      'data-name': n.name,
      ...(n.fixed ? { 'data-xd-fixed': '' } : {}),
      ...(n.stateTarget && stateIds?.has(n.stateTarget)
        ? { 'data-xd-state-target': n.stateTarget, role: 'button', tabindex: '0' }
        : {}),
      ...(n.component ? { 'data-xd-component': n.component.defaultState } : {}),
    };
    if (!n.visible) attributes.hidden = '';
    let tag = isBoard ? 'main' : layout.tag;
    if (interaction.click) {
      const click = interaction.click;
      if (ids.has(click.target)) {
        attributes['data-action'] = click.action;
        attributes['data-target'] = safeId(click.target);
        if (click.action === 'navigate') {
          if (pages[click.target]) attributes['data-page'] = pages[click.target];
          else warnings.push(`${n.name}：導覽目標不是畫板。`);
        }
        attributes['aria-controls'] = safeId(click.target);
        if (tag === 'div' && !n.children.length) tag = 'button';
        if (tag !== 'button') {
          attributes.role = 'button';
          attributes.tabindex = '0';
        }
        attributes['aria-label'] = n.text?.value || n.name;
      } else warnings.push(`${n.name}：互動目標不存在。`);
    }
    if (tag === 'button') attributes.type = 'button';
    if (isBoard) {
      rule.background = paintCss(n.style.fill);
      rule.overflow = 'clip';
      if (options.responsive && !options.scaleArtboard) {
        rule.width = '100%';
        rule['max-width'] = `${b.width}px`;
      }
      if (options.scaleArtboard) {
        attributes['data-scale-width'] = String(b.width);
        attributes['data-scale-height'] = String(b.height);
        rule.margin = '0';
      }
    } else if (options.responsive && !flow) {
      const parentWidth = parent?.bounds.width || board.bounds.width;
      if (layout.responsive === 'scale')
        Object.assign(rule, {
          left: `${round((x / parentWidth) * 100)}%`,
          width: `${round((b.width / parentWidth) * 100)}%`,
        });
      if (layout.responsive === 'stretch')
        Object.assign(rule, { right: `${round(parentWidth - x - b.width)}px`, width: 'auto' });
      if (layout.responsive === 'right') {
        delete rule.left;
        rule.right = `${round(parentWidth - x - b.width)}px`;
      }
      if (layout.responsive === 'center') rule.left = `calc(50% + ${round(x - parentWidth / 2)}px)`;
    }
    if (options.responsive && layout.mode !== 'absolute' && n.children.length) {
      Object.assign(rule, {
        display: layout.mode === 'grid' ? 'grid' : 'flex',
        gap: `${layout.gap}px`,
        padding: `${layout.padding}px`,
        height: 'auto',
        'min-height': `${b.height}px`,
      });
      if (layout.mode === 'grid')
        rule['grid-template-columns'] = `repeat(${layout.columns}, minmax(0, 1fr))`;
      else {
        rule['flex-direction'] = layout.mode === 'row' ? 'row' : 'column';
        rule['align-items'] = 'flex-start';
        rule['flex-wrap'] = 'wrap';
      }
      if (layout.mobileStack)
        mediaRules.push(
          `@media (max-width: ${options.breakpoint}px) { ${selector} { display: flex; flex-direction: column; } ${selector} > .design-node { width: 100%; max-width: 100%; } }`
        );
    }
    if (interaction.position) {
      const p = interaction.position;
      rule.position = p.mode;
      rule.top = `${p.top}px`;
      rule['z-index'] = '10';
      if (p.mode === 'fixed') {
        const world = worldBounds(board, n.id);
        if (world) rule.left = `${round(world.x)}px`;
      }
      if (p.mode === 'sticky' && !flow) {
        // Keep the original block position without consuming subsequent absolute siblings.
        delete rule.left;
        rule['margin-left'] = `${round(x)}px`;
        rule['margin-top'] = `${round(y)}px`;
        warnings.push(`${n.name}：Sticky 建議放在 row／column 群組，並確認容器高度足以捲動。`);
      }
    }
    if (interaction.hover) {
      const h = interaction.hover;
      rule.transition = `translate ${h.duration}ms ease, scale ${h.duration}ms ease, opacity ${h.duration}ms ease`;
      const effect =
        h.effect === 'lift'
          ? 'translate: 0 -6px;'
          : h.effect === 'scale'
            ? 'scale: 1.04;'
            : 'opacity: .65;';
      rules.push(`${selector}:hover, ${selector}:focus-visible { ${effect} }`);
    }
    if (interaction.scroll) {
      attributes['data-reveal'] = '';
      attributes['data-threshold'] = String(interaction.scroll.threshold);
      rule.transition = `opacity ${interaction.scroll.duration}ms ease, translate ${interaction.scroll.duration}ms ease`;
    }
    if (interaction.animation) {
      const a = interaction.animation;
      rule.animation = `xd-${a.effect} ${a.duration}ms ease ${a.repeat ? 'infinite' : '1 both'}`;
    }
    let content = '';
    const complex = n.kind === 'unsupported';
    if (complex) {
      const path = `assets/${safeId(n.id)}.svg`;
      files[path] = renderAsset(
        project.document,
        { ...n, transform: [1, 0, 0, 1, 0, 0], style: { ...n.style, opacity: 1 } },
        { padding: 0 }
      );
      content = `<img class="visual" src="${path}" alt="${esc(n.name)}" />`;
      if (n.children.length)
        warnings.push(`${n.name}：尚未支援的群組保留為 SVG，內部圖層互動不會輸出。`);
    } else if (n.kind === 'text' && n.text) {
      if (flow) {
        Object.assign(rule, appearance(n), { height: 'auto' });
        delete rule['box-shadow'];
        const text = n.text;
        let cursor = 0;
        const chunks: string[] = [];
        for (const run of text.runs) {
          if (run.from > cursor) chunks.push(esc(text.value.slice(cursor, run.from)));
          chunks.push(
            `<span style="${esc(`font-family:${fontStack(run.family)};font-size:${run.size}px;font-weight:${run.weight};font-style:${run.italic ? 'italic' : 'normal'};letter-spacing:${run.spacing}px;color:${run.color}`)}">${esc(text.value.slice(run.from, run.to))}</span>`
          );
          cursor = run.to;
        }
        chunks.push(esc(text.value.slice(cursor)));
        content = chunks.join('');
      } else content = `<span class="visual">${renderLocalSvg(project.document, n)}</span>`;
    } else if (svgAppearance) {
      content = `<span class="visual">${renderLocalSvg(project.document, n)}</span>`;
    } else if (n.kind === 'rect') {
      Object.assign(rule, appearance(n));
      if (n.style.fill.type === 'image') {
        const image = n.style.fill,
          path = assetPaths[image.assetId];
        if (path) {
          rule['background-image'] = `url(${cssString(path)})`;
          rule['background-size'] = image.fit === 'stretch' ? '100% 100%' : image.fit;
          rule['background-position'] = 'center';
          rule['background-repeat'] = 'no-repeat';
        }
      }
      if (n.style.stroke) {
        delete rule.border;
        const stroke = n.style.stroke;
        const strokeShadow = `${stroke.align === 'inside' ? 'inset ' : ''}0 0 0 ${stroke.align === 'center' ? stroke.width / 2 : stroke.width}px ${stroke.color}`;
        rule['box-shadow'] = [strokeShadow, rule['box-shadow']].filter(Boolean).join(', ');
        if (stroke.align === 'center')
          rule['box-shadow'] += `, inset 0 0 0 ${stroke.width / 2}px ${stroke.color}`;
      }
    }
    if (n.style.blendMode) rule['mix-blend-mode'] = n.style.blendMode;
    if (n.style.shadows.length && (n.kind !== 'rect' || svgAppearance) && !complex)
      rule.filter = n.style.shadows
        .map((s) => `drop-shadow(${s.x}px ${s.y}px ${s.blur / 2}px ${s.color})`)
        .join(' ');
    if (!complex)
      content += n.children
        .map((c) => node(c, n, board, fixedAncestor || !!n.fixed, stateIds))
        .join('\n');
    if (n.component) {
      content =
        `<div data-xd-state="${esc(n.component.defaultState)}" class="component-state">${content}</div>` +
        n.component.states
          .map(
            (state) =>
              `<div data-xd-state="${esc(state.id)}" class="component-state" hidden>${node(state.node, n, board, fixedAncestor || !!n.fixed, stateIds)}</div>`
          )
          .join('');
    }
    if (n.clip && !complex) {
      const clipId = `clip-${safeId(n.id)}`;
      rule['clip-path'] = `url(#${clipId})`;
      content = htmlClipDefinition(project.document, n, clipId) + content;
    }
    rules.push(
      `/* ${n.name.replace(/\*\//g, '').replace(/[\r\n]/g, ' ')} */\n${selector} {\n${declarations(rule)}\n}`
    );
    return `<${tag} ${Object.entries(attributes)
      .map(([k, v]) => `${k}="${esc(v)}"`)
      .join(' ')}>\n${content}\n</${tag}>`;
  }
  for (const board of boards) {
    const content = node(board, undefined, board);
    files[pages[board.id]] =
      `<!doctype html>\n<html lang="zh-Hant">\n<head>\n<meta charset="utf-8" />\n<meta name="viewport" content="width=device-width, initial-scale=1" />\n<title>${esc(board.name)} · ${esc(project.document.name)}</title>\n<link rel="stylesheet" href="styles.css" />\n<script src="interactions.js" defer></script>\n</head>\n<body>\n<div class="board-shell" style="max-width:${board.bounds.width}px">\n${content}\n</div>\n</body>\n</html>`;
  }
  files['styles.css'] = [...rules, ...mediaRules].join('\n\n');
  files['interactions.js'] = runtimeSource();
  files['design-tokens.json'] = JSON.stringify(
    {
      colors: [
        ...new Set(all.flatMap((n) => (n.style.fill.type === 'solid' ? [n.style.fill.color] : []))),
      ],
      fonts: [...new Set(all.flatMap((n) => (n.text ? [n.text.family] : [])))],
    },
    null,
    2
  );
  files['README.md'] =
    `# ${project.document.name}\n\n直接開啟 index.html 即可；無需 npm、CDN、React 或 Vue。\n\n- styles.css：以圖層名稱與固定 ID 命名，修改尺寸、定位與排版。\n- interactions.js：原生 JavaScript，負責 click、scroll 與縮放。\n- assets/：內嵌圖片與遮罩群組。\n- design-tokens.json：文件使用的色彩與字型。\n- 每個畫板一個 HTML；navigate 連到對應檔案。\n\n文字在精準定位中使用可編輯的 SVG text/tspan 保留原基線，flow 群組中的文字使用原生 HTML。工具中載入的字型已打包到 assets；其餘字型請在本機安裝。\n響應式不會自動猜測版面：請在工具的排版面板配置群組 flex/grid 及子圖層 pin/stretch。預設保留原始座標。\n\n## 匯出注意事項\n${[...warnings, ...project.document.diagnostics.map((d) => d.message)].map((s) => '- ' + s).join('\n')}\n`;
  return { files, pages, warnings };
}
export function webZip(bundle: WebBundle): Uint8Array {
  return zipSync(
    Object.fromEntries(
      Object.entries(bundle.files).map(([name, data]) => [
        name,
        typeof data === 'string' ? strToU8(data) : data,
      ])
    ),
    { level: 6 }
  );
}

/** Inline resources also work in opaque-origin sandbox documents. */
export function inlineWebPage(bundle: WebBundle, page: string, scriptUrl?: string): string {
  const mime: Record<string, string> = {
    svg: 'image/svg+xml',
    png: 'image/png',
    jpg: 'image/jpeg',
    webp: 'image/webp',
    gif: 'image/gif',
    woff2: 'font/woff2',
    woff: 'font/woff',
    ttf: 'font/ttf',
    otf: 'font/otf',
  };
  const assets: Record<string, string> = {};
  for (const [path, value] of Object.entries(bundle.files))
    if (path.startsWith('assets/')) {
      const bytes = typeof value === 'string' ? new TextEncoder().encode(value) : value;
      let binary = '';
      for (let i = 0; i < bytes.length; i += 32768)
        binary += String.fromCharCode(...bytes.subarray(i, i + 32768));
      assets[path] =
        `data:${mime[path.split('.').at(-1)!] ?? 'application/octet-stream'};base64,${btoa(binary)}`;
    }
  const inline = (s: string) => s.replace(/assets\/[a-zA-Z0-9.-]+/g, (p) => assets[p] ?? p);
  const css = inline(String(bundle.files['styles.css'])).replaceAll('<', '\\3c ');
  const script = scriptUrl
    ? `<script src="${esc(scriptUrl)}" defer></script>`
    : `<script>${String(bundle.files['interactions.js'])}</script>`;
  return inline(String(bundle.files[page]))
    .replace('<link rel="stylesheet" href="styles.css" />', `<style>${css}</style>`)
    .replace('<script src="interactions.js" defer></script>', script);
}

/** The trusted runtime is a packaged app resource; no Blob fetches from a sandbox. */
export function createPreview(
  bundle: WebBundle,
  boardId: string
): { html: string; dispose: () => void } {
  const page = bundle.pages[boardId];
  if (!page) throw new Error('找不到預覽畫板。');
  return {
    html: inlineWebPage(bundle, page, new URL(previewRuntimeUrl, window.location.href).href),
    dispose: () => {},
  };
}
